<?php


/*  Declaracion de funciones matematicas
    -sumar: suma dos números
    -restar: resta dos números
    -multiplicar: multiplica dos números
    -dividir: divide dos números
*/

function sumar($a, $b) {
 return $a + $b;
}

function restar($a, $b) {
 return $a - $b;
}

function multiplicar($a, $b) {
 return $a * $b;
}

function dividir($a, $b) {
 return $a / $b;
}